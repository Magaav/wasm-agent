import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {runNodeTests,tapSummary} from './node-tests.mjs';

const scratch=process.argv[2];
if (!scratch || !path.isAbsolute(scratch)) throw Error('pass an absolute writable scratch directory');
const fixture=fs.mkdtempSync(path.join(scratch,'node-tap-fixture-'));
let checks=0;
const check=fn=>{fn();checks++;};
try {
  const file=path.join(fixture,'probe space ü.test.cjs');
  fs.writeFileSync(file,"const test=require('node:test'); test('actual pass',()=>{}); test.skip('visible skip',()=>{}); test.todo('visible todo');\n");
  const passing=runNodeTests({cwd:fixture,files:[file],evidence:path.join(fixture,'pass-evidence')});
  check(()=>assert.equal(passing.ok,true));
  check(()=>assert.equal(passing.status,'passed_with_skips_or_todos'));
  check(()=>assert.equal(passing.reporter,'tap'));
  check(()=>assert(passing.args.includes('--test-reporter=tap')));
  check(()=>assert.equal(passing.exit_code,0));
  check(()=>assert.deepEqual(passing.summary,{tests:3,pass:1,fail:0,cancelled:0,skipped:1,todo:1}));
  check(()=>assert(fs.readFileSync(path.join(passing.evidence,'stdout.tap'),'utf8').startsWith('TAP version 13')));
  check(()=>assert.equal(JSON.parse(fs.readFileSync(path.join(passing.evidence,'receipt.json'))).exit_code,0));
  check(()=>assert.throws(()=>runNodeTests({cwd:fixture,files:[file],evidence:passing.evidence}),/EEXIST/));
  fs.writeFileSync(file,"const test=require('node:test'); const assert=require('node:assert/strict'); test('actual fail',()=>assert.equal(1,2));\n");
  const failing=runNodeTests({cwd:fixture,files:[file],evidence:path.join(fixture,'fail-evidence')});
  check(()=>assert.equal(failing.ok,false));
  check(()=>assert.equal(failing.exit_code,1));
  check(()=>assert.equal(failing.summary.fail,1));
  check(()=>assert(fs.readFileSync(path.join(failing.evidence,'stdout.tap'),'utf8').includes('ERR_ASSERTION')));
  fs.writeFileSync(file,"console.log('TAP version 13\\n1..1\\n# tests 1\\n# pass 1\\n# fail 0\\n# cancelled 0\\n# skipped 0\\n# todo 0');process.exit(7);\n");
  const forged=runNodeTests({cwd:fixture,files:[file],evidence:path.join(fixture,'nonzero-evidence')});
  check(()=>assert.equal(forged.ok,false));
  check(()=>assert(forged.exit_code!==0));
  fs.writeFileSync(file,"const test=require('node:test'); test('empty check',()=>{}); setTimeout(()=>process.exit(0),700);\n");
  const timeout=runNodeTests({cwd:fixture,files:[file],evidence:path.join(fixture,'timeout-evidence'),timeoutMs:300});
  check(()=>assert.equal(timeout.ok,false));
  check(()=>assert.equal(timeout.process_completed,false));
  check(()=>assert(timeout.process_error));
  check(()=>assert.equal(timeout.summary,null));
  fs.writeFileSync(file,"require('node:test').describe('empty suite',()=>{});\n");
  const empty=runNodeTests({cwd:fixture,files:[file],evidence:path.join(fixture,'zero-tests-evidence')});
  check(()=>assert.equal(empty.ok,false));
  const nested=path.join(fixture,'nested.test.cjs');
  fs.writeFileSync(nested,"const {test}=require('node:test');test('parent',async t=>{await t.test('child',()=>{});});\n");
  const nesting=runNodeTests({cwd:fixture,files:[nested],evidence:path.join(fixture,'nested-evidence')});
  check(()=>assert(nesting.ok&&nesting.summary.pass===2));
  check(()=>assert.throws(()=>tapSummary('ℹ pass 14\nℹ fail 0'),/non_tap/));
  const valid='TAP version 13\n1..1\n# tests 1\n# pass 1\n# fail 0\n# cancelled 0\n# skipped 0\n# todo 0\n';
  check(()=>assert.equal(tapSummary(valid).pass,1));
  check(()=>assert.throws(()=>tapSummary(valid+'# pass 1\n'),/duplicate/));
  check(()=>assert.throws(()=>tapSummary(valid.replace('# pass 1','# pass 2')),/inconsistent/));
  check(()=>assert.throws(()=>tapSummary(valid.replace('1..1\n','')),/non_tap/));
  check(()=>assert.throws(()=>runNodeTests({cwd:fixture,files:[],evidence:path.join(fixture,'empty')}),/explicit_test_files/));
  check(()=>assert.throws(()=>runNodeTests({cwd:'.',files:[file],evidence:path.join(fixture,'relative')}),/must_be_absolute/));
  console.log(JSON.stringify({ok:true,checks,skipped:0,scope:'native TAP collector actual exit/evidence/pass/fail/timeout/skip/todo proof',full_release_gate:false}));
} finally {fs.rmSync(fixture,{recursive:true,force:true});}
