-- Every tool answer carries one status, stamped by the dispatcher (operator 14/11: "return 200 for
-- success", engineering law): 200 done, 202 running/queued, 400 fix the call, 403, 404, 500 world failed.
local json=dofile('lua/vendor/json.lua')
local status=dofile('lua/core/status.lua')
local checks=0;local function check(v,label)assert(v,label);checks=checks+1 end
check(status.of({ok=true,content='x'})==200,'success is 200')
check(status.of({ok=true,state='pending',id=3})==202,'queued is 202')
check(status.of({error='schema_extra:arguments.query (accepted: limit, q)'})==400,'a wrong argument is 400')
check(status.of({error='SyntaxError: unexpected token',code='SyntaxError'})==400,'a script that did not compile is 400')
check(status.of({error='forbidden_for_role:guest'})==403,'not allowed is 403')
check(status.of({error='tools.read failed: ...',code='read_file_missing'})==404,'a missing file is 404')
check(status.of({ok=false,state='failed',process_exit_code=2})==500,'a command that ran and failed is 500')
check(status.of({ok=true,status=200,message_id='X'})==200,'a tool that states its status keeps it')
local memory=dofile('lua/core/memory.lua');memory.setup()
local tools=dofile('lua/core/tools.lua');local policy=dofile('lua/core/codemode_policy.lua')
local sid=memory.start_session('','status',{user_id='master'})
local ctx={session_id=sid,user_id='master'};policy.pin(memory,'master',ctx)
local r=tools.dispatch(memory,'codemode',{code='return 1;'},'master',ctx)
check(r.status==200,'a script that ran answers 200: '..json.encode(r):sub(1,200))
r=tools.dispatch(memory,'codemode',{code='const = ;'},'master',ctx)
check(r.status==400,'a script that did not compile answers 400: '..tostring(r.status))
r=tools.dispatch(memory,'no_such_tool_anywhere',{},'master',ctx)
check(type(r.status)=='number' and r.status>=400,'an unknown tool answers 4xx: '..json.encode(r):sub(1,200))
check(policy.guidance:find('Every answer has a status: 200 done',1,true)~=nil,'the guidance names the statuses')
print(json.encode({ok=true,checks=checks}))
