    check(chronologicalOrder.indexOf(beforeComment)<commentaryAt && chronologicalOrder.indexOf(afterComment)>commentaryAt,'repaint preserves model waits on both sides of commentary', {order:chronologicalOrder.map(e=>e.tagName+':'+e.textContent)});
    conversationEpoch++;
    observedRun={session:chatSession,run_id:9009,ms:0};
    const summaryUser={...first,id:'summary-user',seq:700};
    repaintMessages([summaryUser],{active:true,notify:false});
