    repaintMessages([{...first,id:'queued-user',seq:400}],{active:true,notify:false});
    check(runStepState.active.label==='Working — waiting for the next step', 'unknown admission state uses a neutral observed phase', {run:observedRun,label:runStepState.active.label});
    observedRun=activeRun({node_threads:[{session:chatSession,run_id:9005,role:'runs',label:'POST /chat',ms:1000}]});
    ensureObservedRunStep(observedRun);
    check(!runStepState.active.label.includes('Queued'), 'same run phase changes when queued admission starts', {label:runStepState.active.label});
    conversationEpoch++;
    observedRun={session:chatSession,run_id:9006,ms:0};
    repaintMessages([{...first,id:'progress-user',seq:500}],{active:true,notify:false});
    handleEvent({type:'commentary',text:'Still inspecting worker effects',message_id:'progress-only'});
    const progressStep=runStepState.active.node;
    observedRun={session:chatSession,run_id:9007,ms:0};
