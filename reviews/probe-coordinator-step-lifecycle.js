    check(progressStep.dataset.state!=='completed', 'commentary without final answer cannot complete previous phase', {state:progressStep.dataset.state});
    const historical=transcript.querySelector('wa-message.assistant');
    const historicalOrder=Array.from(historical.body.children);
    check(historicalOrder.findIndex(e=>e.tagName==='WA-STEP') < historicalOrder.findIndex(e=>e.tagName==='WA-COMMENTARY'), 'repaint keeps early phase before commentary payload', {order:historicalOrder.map(e=>e.tagName)});
